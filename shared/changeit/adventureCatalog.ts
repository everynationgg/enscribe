export const ALL_CHANGEIT_ADVENTURE_STAGES: ChangeItAdventureStageDefinition[] =
  CHANGEIT_ADVENTURE_CHAPTERS.flatMap((c) => c.stages);

export function getChangeItAdventureStage(
  stageId: string
): ChangeItAdventureStageDefinition | undefined {
  return ALL_CHANGEIT_ADVENTURE_STAGES.find((s) => s.id === stageId);
}

export function computeAdventureStars(
  movesUsed: number,
  minMoves: number,
  hintsUsed: number
): 1 | 2 | 3 {
  let stars: 1 | 2 | 3 =
    movesUsed <= minMoves ? 3 : movesUsed <= minMoves + 2 ? 2 : 1;
  if (hintsUsed > 0 && stars === 3) {
    stars = 2;
  }
  return stars;
}
