function shuffleInPlace<T>(arr: T[]): T[] {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * Tracks recently generated chains, starting words, individual words, and directed edges
 * so repeated invocations never serve the same words or paths back-to-back.
 */
export class ChainHistoryTracker {
  private recentChains: string[] = [];
  private recentChainSet = new Set<string>();
  private recentStartWords: string[] = [];
  private recentStartSet = new Set<string>();
  private recentWordsQueue: string[] = [];
  private recentWordCounts = new Map<string, number>();
  private recentEdges: string[] = [];
  private recentEdgeSet = new Set<string>();

  constructor(
    private limits = {
      chains: 250,
      starts: 60,
      words: 180,
      edges: 300,
    }
  ) {}

  hasChain(signature: string): boolean {
    return this.recentChainSet.has(signature);
  }

  hasStartWord(word: string): boolean {
    return this.recentStartSet.has(word);
  }

  hasEdge(from: string, to: string): boolean {
    return this.recentEdgeSet.has(`${from}>${to}`);
  }

  wordPenalty(word: string): number {
    return this.recentWordCounts.get(word) ?? 0;
  }

  record(words: string[]): void {
    if (words.length === 0) return;
    const sig = words.join('>');
    if (!this.recentChainSet.has(sig)) {
      this.recentChains.push(sig);
      this.recentChainSet.add(sig);
      while (this.recentChains.length > this.limits.chains) {
        const dropped = this.recentChains.shift()!;
        this.recentChainSet.delete(dropped);
      }
    }

    const start = words[0];
    this.recentStartWords.push(start);
    this.recentStartSet.add(start);
    while (this.recentStartWords.length > this.limits.starts) {
      const dropped = this.recentStartWords.shift()!;
      if (!this.recentStartWords.includes(dropped)) {
        this.recentStartSet.delete(dropped);
      }
    }

    for (let i = 0; i < words.length; i++) {
      const w = words[i];
      this.recentWordsQueue.push(w);
      this.recentWordCounts.set(w, (this.recentWordCounts.get(w) ?? 0) + 1);
      while (this.recentWordsQueue.length > this.limits.words) {
        const dropped = this.recentWordsQueue.shift()!;
        const c = (this.recentWordCounts.get(dropped) ?? 1) - 1;
        if (c <= 0) this.recentWordCounts.delete(dropped);
        else this.recentWordCounts.set(dropped, c);
      }

      if (i > 0) {
        const edge = `${words[i - 1]}>${w}`;
        if (!this.recentEdgeSet.has(edge)) {
          this.recentEdges.push(edge);
          this.recentEdgeSet.add(edge);
          while (this.recentEdges.length > this.limits.edges) {
            const droppedEdge = this.recentEdges.shift()!;
            this.recentEdgeSet.delete(droppedEdge);
          }
        }
      }
    }
  }
}

