export function normalizeTwistItWord(raw: string): string {
  return String(raw || '').toUpperCase().replace(/[^A-Z]/g, '');
}

export function canFormFromLetters(word: string, availableLetters: string[]): boolean {
  const counts = new Map<string, number>();
  for (const ch of availableLetters) {
    const clean = ch.toUpperCase();
    counts.set(clean, (counts.get(clean) || 0) + 1);
  }
  for (const ch of word) {
    const remaining = counts.get(ch) || 0;
    if (remaining <= 0) return false;
    counts.set(ch, remaining - 1);
  }
  return true;
}

export function mulberry32(seed: number): () => number {
  let t = seed >>> 0;
  return () => {
    t += 0x6d2b79f5;
    let x = t;
    x = Math.imul(x ^ (x >>> 15), x | 1);
    x ^= x + Math.imul(x ^ (x >>> 7), x | 61);
    return ((x ^ (x >>> 14)) >>> 0) / 4294967296;
  };
}

export function scrambleSixLetters(letters: string[], seed: number, avoidExactWord?: string): string[] {
  const rng = mulberry32(seed);
  const arr = [...letters.map((l) => l.toUpperCase())];
  for (let attempt = 0; attempt < 8; attempt++) {
    for (let i = arr.length - 1; i > 0; i--) {
      const j = Math.floor(rng() * (i + 1));
      const tmp = arr[i];
      arr[i] = arr[j];
      arr[j] = tmp;
    }
    if (!avoidExactWord || arr.join('') !== avoidExactWord.toUpperCase()) {
      break;
    }
  }
  if (avoidExactWord && arr.join('') === avoidExactWord.toUpperCase() && arr.length >= 2) {
    const tmp = arr[0];
    arr[0] = arr[arr.length - 1];
    arr[arr.length - 1] = tmp;
  }
  return arr;
}

export function twistTileIndices(currentIndices: number[], seed = Date.now()): number[] {
  const next = [...currentIndices];
  const rng = mulberry32(seed ^ (currentIndices.join('').length * 997));
  for (let i = next.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    const tmp = next[i];
    next[i] = next[j];
    next[j] = tmp;
  }
  if (next.every((v, idx) => v === currentIndices[idx]) && next.length >= 2) {
    const tmp = next[0];
    next[0] = next[1];
    next[1] = tmp;
  }
  return next;
}

export function validateTwistItWordAgainstAnswers(
  rawWord: string,
  availableLetters: string[],
  requiredAnswers: string[],
  foundWords: ReadonlySet<string>
):
  | { ok: true; word: string; answerIndex: number }
  | { ok: false; word: string; errorCode: TwistItSubmitErrorCode; message: string } {
  const word = normalizeTwistItWord(rawWord);
  if (word.length < 3) {
    return {
      ok: false,
      word,
      errorCode: 'TOO_SHORT',
      message: 'Words must be at least 3 letters long.',
    };
  }
  if (word.length > 6) {
    return {
      ok: false,
      word,
      errorCode: 'TOO_LONG',
      message: 'Words can use at most 6 letters.',
    };
  }
  if (!canFormFromLetters(word, availableLetters)) {
    return {
      ok: false,
      word,
      errorCode: 'INVALID_LETTERS',
      message: 'Use only the six available letter tiles once each.',
    };
  }
  if (foundWords.has(word)) {
    return {
      ok: false,
      word,
      errorCode: 'ALREADY_FOUND',
      message: `${word} was already found!`,
    };
  }
  const answerIndex = requiredAnswers.indexOf(word);
  if (answerIndex < 0) {
    return {
      ok: false,
      word,
      errorCode: 'NOT_IN_PUZZLE',
      message: `${word} is not in this puzzle's answer list.`,
    };
  }
  return { ok: true, word, answerIndex };
}

export function pickTwistItPuzzle(
  excludeIds: ReadonlySet<string> | string[] = [],
  seed = Date.now()
): TwistItPuzzleDefinition {
  const excludeSet = excludeIds instanceof Set ? excludeIds : new Set(excludeIds);
  const candidates = TWISTIT_PUZZLE_CATALOG.filter((p) => !excludeSet.has(p.id));
  const pool = candidates.length > 0 ? candidates : TWISTIT_PUZZLE_CATALOG;
  const rng = mulberry32(seed);
  const index = Math.floor(rng() * pool.length);
  return pool[index] || TWISTIT_PUZZLE_CATALOG[0];
}
